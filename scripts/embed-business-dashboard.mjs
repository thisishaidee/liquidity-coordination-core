import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(resolve(root, "public/dashboard.html"), "utf8");
const connector = await build({
  entryPoints: [resolve(root, "scripts/okx-wallet-connector.js")],
  bundle: true,
  write: false,
  format: "iife",
  target: ["es2020"],
  platform: "browser",
  minify: true
});
const bundledConnector = connector.outputFiles[0]?.text;
if (!bundledConnector) throw new Error("OKX wallet connector bundle was not generated.");
const generatedConnector = `// Generated by scripts/embed-business-dashboard.mjs.\\nexport const okxWalletConnectorJs = ${JSON.stringify(bundledConnector)};\\n`;
writeFileSync(resolve(root, "src/okx-wallet-connector.ts"), generatedConnector);
const generatedDashboard = `// Generated from public/dashboard.html by scripts/embed-business-dashboard.mjs.\\nexport const businessDashboardHtml = ${JSON.stringify(html)};\\n`;
writeFileSync(resolve(root, "src/business-dashboard.ts"), generatedDashboard);
